    print("[3/5] กำลังสกัดคุณลักษณะด้วย TF-IDF Vectorizer ร่วมกับ PyThaiNLP...")
    vectorizer = TfidfVectorizer(
        tokenizer=thai_text_tokenizer,
        token_pattern=None,  # ปิด pattern เริ่มต้นเพื่อใช้ custom tokenizer
        ngram_range=(1, 2),  # ใช้ทั้งคำเดี่ยว (Unigram) และคำคู่ (Bigram)
        min_df=2,
        sublinear_tf=True
    )

