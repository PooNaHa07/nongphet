# ส่วนที่ 2: การทำความสะอาดข้อความและตัดคำภาษาไทย (Preprocessing & Tokenization)
# ==============================================================================
def thai_text_tokenizer(text):
    """
    ฟังก์ชันทำความสะอาดข้อความและตัดคำภาษาไทยด้วยเอ็นจิ้น 'newmm' ของ PyThaiNLP
    """
    if not isinstance(text, str):
        return []
    # 1. ปรับรูปสระและวรรณยุกต์ที่พิมพ์ซ้ำหรือผิดลำดับให้เป็นมาตรฐาน
    cleaned = normalize(text.strip().lower())
    # 2. ตัดคำด้วยพจนานุกรม Maximum Matching (newmm)
    tokens = word_tokenize(cleaned, engine="newmm", keep_whitespace=False)
    # 3. กรองเอาเฉพาะคำที่มีความหมาย (ตัดสัญลักษณ์พิเศษออก)
    tokens = [t for t in tokens if len(t.strip()) > 0]
    return tokens


