def augment_thai_dataset(seed_dict, target_per_class=400):
    """
    ฟังก์ชันขยายขนาดชุดข้อมูล (Data Augmentation) สำหรับภาษาไทย
    โดยการผสมคำขึ้นต้น (Prefixes) และคำลงท้าย/คำสร้อย (Suffixes) ตามธรรมชาติของการพูด
    รวม 5 คลาส คลาสละ 300 ตัวอย่าง = รวม 1,500 ตัวอย่าง
    """
    prefixes = [
        "", "น้องเพชร ", "น้องเพชรครับ ", "น้องเพชรคะ ", "สอบถามหน่อย ",
        "อยากรู้ว่า ", "ช่วยบอกทีว่า ", "ขอถามนิดนึง ", "รบกวนถามหน่อย ", "อยากทราบว่า ",
        "ขอข้อมูล ", "น้องเพชรช่วยดู ", "บอกหน่อยจ้า ", "สงสัยว่า ", "ขอสอบถาม ", "อยากได้ข้อมูล "
    ]
    suffixes = [
        "", " ครับ", " ค่ะ", " นะครับ", " นะคะ", " จ๊ะ", " หน่อยครับ",
        " หน่อยค่ะ", " ได้ไหม", " บ้างครับ", " บ้างคะ", " ช่วยแนะนำที",
        " หน่อยดิ", " มีไหมครับ", " มีไหมคะ", " ได้หรือเปล่า", " จ้า", " ทีค่ะ", " หน่อยสิ"
    ]

    rows = []
    for intent, phrases in seed_dict.items():
        generated = set()
        # ใส่ประโยคต้นฉบับทั้งหมดลงไปก่อน
        for p in phrases:
            generated.add(p.strip())

        # สุ่มผสมคำหน้า-คำหลังจนครบจำนวนเป้าหมายต่อคลาส
        attempts = 0
        while len(generated) < target_per_class and attempts < 10000:
            base = random.choice(phrases)
            pre = random.choice(prefixes)
            suf = random.choice(suffixes)
            combined = f"{pre}{base}{suf}".strip()
            generated.add(combined)
            attempts += 1

        for text in list(generated)[:target_per_class]:
            rows.append({"text": text, "intent": intent})

    df = pd.DataFrame(rows)
    # สลับลำดับข้อมูลแบบสุ่ม (Shuffle)
    df = df.sample(frac=1.0, random_state=RANDOM_SEED).reset_index(drop=True)
    return df


