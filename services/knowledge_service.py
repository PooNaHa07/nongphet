            "'เพชรบุรีธานีสามวังแสนสง่า  หาดชะอำงามตาชวนหลงใหล\n"
            "หม้อแกงหอมตาลโตนดฉ่ำชื่นใจ  มาเมื่อไหร่ก็อบอุ่นทุกเวลา\n"
